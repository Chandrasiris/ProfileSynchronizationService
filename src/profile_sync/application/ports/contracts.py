from typing import Protocol
from uuid import UUID
from profile_sync.domain.models import Mapping

class ContactProtector(Protocol):
    def email_hash(self, normalized: str) -> str: ...
    def phone_hash(self, normalized: str) -> str: ...
    def encrypt(self, value: str) -> str: ...

class MappingRepository(Protocol):
    def find(self, headers: list[str], context: str) -> dict[str, Mapping]: ...
    def save_approved(self, mappings: list[Mapping], context: str, approved_by: UUID) -> None: ...

class FieldMappingAgent(Protocol):
    def suggest(self, headers: list[str], context: str, allowed_fields: list[str]) -> list[Mapping]: ...

class ProfileTagAgent(Protocol):
    def suggest(self, project_name: str, headers: list[str]) -> list[str]: ...

class MetadataSanitizer(Protocol):
    def approve(self, project_name: str, headers: list[str]) -> None: ...
